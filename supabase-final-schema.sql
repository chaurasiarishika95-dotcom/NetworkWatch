-- Network Watch: persist only actual external observations and the app's computed decisions.
-- Run in Supabase SQL Editor. Does NOT fabricate shipment/customer data.
create table if not exists public.network_observations (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('weather','traffic','route_analysis')),
  entity_key text not null,
  source text not null,
  observed_at timestamptz not null default now(),
  is_live boolean not null default false,
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists network_observations_kind_entity_time_idx
  on public.network_observations (kind, entity_key, observed_at desc);
create index if not exists network_observations_created_at_idx
  on public.network_observations (created_at desc);
alter table public.network_observations enable row level security;
revoke all on public.network_observations from anon, authenticated;

-- Scenario/decision history table used by the existing app.
create table if not exists public.scenario_runs (
  id uuid primary key default gen_random_uuid(),
  scenario_key text not null,
  scenario_name text not null,
  summary text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists scenario_runs_created_at_idx on public.scenario_runs (created_at desc);
alter table public.scenario_runs enable row level security;
revoke all on public.scenario_runs from anon, authenticated;
